def test_bundle_writes_twenty_four_drafts_and_review_zip(
    tmp_path: Path, project_root: Path
) -> None:
    import shutil

    shutil.copytree(project_root / "knowledge", tmp_path / "knowledge")
    (tmp_path / "artifacts").mkdir()
    # The v1 writer pins grpo_reward.py bytes; give the isolated copy src/.
    (tmp_path / "src/enterprise_memory_mlx").mkdir(parents=True)
    shutil.copy2(
        project_root / "src/enterprise_memory_mlx/grpo_reward.py",
        tmp_path / "src/enterprise_memory_mlx/grpo_reward.py",
    )
    summary = write_annotation_bundle(tmp_path)
    assert summary["counts"] == {
        "source_cases_inspected": 24,
        "fully_mapped_draft_cases": 24,
        "unresolved_cases": 0,
        "review_complete_cases": 0,
    }
    assert summary["human_attested"] is False
    assert summary["training_authorized"] is False
    assert summary["historical_stops"] == HISTORICAL_STOPS
    destination = tmp_path / "artifacts/qwen4b-typed-action-annotation-v1"
    drafts = [
        json.loads(line)
        for line in (destination / "typed-targets.draft.jsonl").read_text().splitlines()
        if line
    ]
    assert [row["case_id"] for row in drafts] == list(EXPECTED_TRAIN)
    assert all(row["authorship"] == "model_authored" for row in drafts)
    assert all(row["human_attested"] is False for row in drafts)
    zip_path = destination / "qwen4b-typed-action-annotation-v1-review.zip"
    digest = (destination / "qwen4b-typed-action-annotation-v1-review.sha256").read_text().strip()
    assert zip_path.is_file()
    assert len(digest) == 64
    packet = json.loads((destination / "review-packet/packet_manifest.json").read_text())
    assert packet["status"] == "awaiting_model_advisory_review"
    assert packet["review_complete_cases"] == 0
    # The frozen, externally reviewed packet in the real artifacts tree must
    # never be regenerated by running the test suite.
    pinned = (
        project_root
        / "artifacts/qwen4b-typed-action-annotation-v1/qwen4b-typed-action-annotation-v1-review.zip"
    )
    if pinned.is_file():
        from enterprise_memory_mlx.grpo_data import file_sha256
        from enterprise_memory_mlx.typed_action_annotation_v2 import V1_REVIEW_ZIP_SHA256

        assert file_sha256(pinned) == V1_REVIEW_ZIP_SHA256


def test_structural_validation_does_not_self_certify_semantics(project_root: Path) -> None:
    cases = load_train_cases(project_root)
    from enterprise_memory_mlx.typed_action_annotation import build_drafts

    drafts = build_drafts(cases)
    result = validate_drafts(drafts, cases)
    assert result["failures"] == []
    assert result["source_to_action_annotation"] == "requires_substantive_review"
    assert result["circular_self_certification"] is False
    assert result["action_substitution_counterexample"]["equivalent"] is False
    assert result["request_evidence_versus_record_completion"]["equivalent"] is False
    assert result["request_exception_versus_grant"]["equivalent"] is False
    assert result["equivalent_ordering_harmless"] is True
    assert result["duplicates_do_not_complete"] is True


def test_action_identities_are_unambiguous_and_alternatives_kept(project_root: Path) -> None:
    cases = load_train_cases(project_root)
    from enterprise_memory_mlx.typed_action_annotation import build_drafts

    drafts = {row["case_id"]: row for row in build_drafts(cases)}
    invoice = drafts["CTS3-QUAL-009"]["proposed_training_target"]["assessments"][0]
    operations = [item["operation"] for item in collect_actions(invoice["remedy"])]
    assert operations == ["correct_nonconformance", "request_alternative_authorization"]
    assert "grant_or_waive" not in operations
    unknown = drafts["CTS3-QUAL-005"]["proposed_training_target"]["assessments"][0]
    assert collect_actions(unknown["remedy"])[0]["operation"] == "request_evidence"
    nested = drafts["CTS3-QUAL-024"]["proposed_training_target"]["assessments"][0]
    nested_ops = [item["operation"] for item in collect_actions(nested["remedy"])]
    assert nested_ops == ["perform_unmet_control", "perform_unmet_control"]
    assert {item["condition_id"] for item in collect_actions(nested["remedy"])} == {
        "security_questionnaire_complete",
        "data_processing_terms_signed",
    }


def test_answer_blind_schema_admits_wrong_choices() -> None:
    schema = output_schema()
    assert ANNOTATION_ID in schema["$id"]
    for example in wrong_but_admissible_examples():
        assert validate_against_schema(example, schema) == []
    skipped = _action("record_completion", "identity_check_complete", "PROC-VEND-001")
    performed = _action("perform_unmet_control", "identity_check_complete", "PROC-VEND-001")
    assert trees_equivalent(skipped, performed) is False
    swapped = _group(
        "any_of",
        _action("perform_unmet_control", "sanctions_check_complete", "PROC-VEND-001"),
        _action("perform_unmet_control", "conflict_check_complete", "PROC-VEND-001"),
    )
    original = _group(
        "all_of",
        _action("perform_unmet_control", "sanctions_check_complete", "PROC-VEND-001"),
        _action("perform_unmet_control", "conflict_check_complete", "PROC-VEND-001"),
    )
    assert trees_equivalent(swapped, original) is False


